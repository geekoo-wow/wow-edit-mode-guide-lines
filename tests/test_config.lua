-- tests/test_config.lua — SavedVariables loading and the config operations
-- the panel and slash command use.

local T = ...
local test, eq, truthy = T.test, T.eq, T.truthy

-- Counts ns.OnConfigChanged calls, which is how the UI learns of changes.
local function changes(ns)
  local n = 0
  ns.OnConfigChanged = function() n = n + 1 end
  return function() return n end
end

test("a fresh install gets the defaults and an empty guide list", function()
  local ns = T.load(nil)
  eq(ns.db.enabled, true)
  eq(ns.db.showOutsideEditMode, false)
  eq(ns.db.thickness, 1)
  eq(ns.db.guides, {})
  eq(ns.db.version, ns.DEFAULTS.version)
  truthy(ns.db.guides ~= ns.DEFAULTS.guides, "a copy, so edits can't reach the defaults")
end)

test("hand-edited SavedVariables are cleaned up without raising", function()
  local ns = T.load({
    enabled = "yes", thickness = "x", aboveFrames = true,
    guides = { { orientation = "v", percent = 50 }, "junk", { orientation = "h", percent = 200 },
      [7] = { orientation = "h", percent = "25", color = "red", enabled = false } },
  })
  eq(ns.db.enabled, true, "non-boolean counts as missing")
  eq(ns.db.thickness, 1)
  eq(ns.db.aboveFrames, true)
  eq(#ns.db.guides, 2)
  eq(ns.db.guides[1].orientation, "vertical")
  eq(ns.db.guides[2], { orientation = "horizontal", percent = 25, color = ns.Guides.ParseColor("red"), enabled = false })
  eq(T.load({ guides = "none" }).db.guides, {})
  eq(T.load("not a table").db.guides, {})
end)

test("Add appends a guide and reports its number", function()
  local ns = T.load()
  local count = changes(ns)
  eq({ ns.Config.Add("v", "50", "green") }, { 1 })
  eq({ ns.Config.Add("h", 33.3) }, { 2 })
  eq(ns.db.guides[1], { orientation = "vertical", percent = 50, color = ns.Guides.ParseColor("green"), enabled = true })
  eq(ns.db.guides[2].orientation, "horizontal")
  eq(ns.db.guides[2].percent, 33.3)
  eq(ns.Config.Count(), 2)
  eq(count(), 2)
end)

test("Add refuses bad input and duplicates, changing nothing", function()
  local ns = T.load()
  ns.Config.Add("v", 50)
  local count = changes(ns)
  local i, err = ns.Config.Add("v", 50, "red")
  eq(i, nil)
  truthy(err:match("already"), err)
  i, err = ns.Config.Add("v", "abc")
  eq(i, nil)
  truthy(err:match("percentage"), err)
  i, err = ns.Config.Add("z", 10)
  eq(i, nil)
  truthy(err:match("orientation"), err)
  i, err = ns.Config.Add("v", 10, "nope")
  eq(i, nil)
  truthy(err:match("color"), err)
  eq(ns.Config.Count(), 1)
  eq(count(), 0)
end)

test("Remove and Clear", function()
  local ns = T.load()
  ns.Config.Add("v", 50)
  ns.Config.Add("h", 50)
  ns.Config.Add("v", 20)
  eq(ns.Config.Remove(2), true)
  eq(ns.Config.Count(), 2)
  eq(ns.Config.Get(2).percent, 20, "the later guide moved up")
  eq(ns.Config.Remove(5), false)
  local list = ns.db.guides
  eq(ns.Config.Clear(), 2)
  eq(ns.Config.Count(), 0)
  truthy(ns.db.guides == list, "cleared in place")
  eq(ns.Config.Clear(), 0)
end)

test("SetPercent, SetOrientation, Flip, SetColor and SetEnabled edit a guide", function()
  local ns = T.load()
  ns.Config.Add("v", 50)
  ns.Config.Add("v", 20)
  local count = changes(ns)
  eq(ns.Config.SetPercent(1, "60"), nil)
  eq(ns.Config.Get(1).percent, 60)
  truthy(ns.Config.SetPercent(1, "20"):match("already"), "would duplicate guide 2")
  truthy(ns.Config.SetPercent(1, "x"):match("percentage"))
  eq(ns.Config.SetPercent(9, 10), "no such guide")
  eq(ns.Config.SetOrientation(1, "h"), nil)
  eq(ns.Config.Get(1).orientation, "horizontal")
  truthy(ns.Config.SetOrientation(1, "d"):match("orientation"))
  eq(ns.Config.Flip(1), nil)
  eq(ns.Config.Get(1).orientation, "vertical")
  eq(ns.Config.SetOrientation(2, "h"), nil)
  eq(ns.Config.SetPercent(2, 60), nil)
  truthy(ns.Config.Flip(1):match("already"), "flipping onto guide 2 after it moved")
  eq(ns.Config.SetColor(1, "#ff0000"), nil)
  eq(ns.Config.Get(1).color, { r = 1, g = 0, b = 0, a = 1 })
  eq(ns.Config.SetColor(1, { r = 0, g = 0, b = 1, a = 0.5 }), nil)
  eq(ns.Config.Get(1).color.a, 0.5)
  truthy(ns.Config.SetColor(1, "nope"):match("color"))
  eq(ns.Config.SetEnabled(1, false), nil)
  eq(ns.Config.Get(1).enabled, false)
  eq(ns.Config.Toggle(1), nil)
  eq(ns.Config.Get(1).enabled, true)
  eq(ns.Config.Toggle(9), "no such guide")
  eq(count(), 9, "only successful edits notify")
end)

test("settings: only the booleans in DEFAULTS, plus a validated thickness", function()
  local ns = T.load()
  local count = changes(ns)
  eq(ns.Config.SetSetting("enabled", nil), nil)
  eq(ns.db.enabled, false)
  eq(ns.Config.SetSetting("showOutsideEditMode", 1), nil)
  eq(ns.db.showOutsideEditMode, true)
  eq(ns.Config.SetSetting("thickness", true), "no such setting")
  eq(ns.Config.SetSetting("version", true), "no such setting")
  eq(ns.db.thickness, 1)
  eq(ns.Config.SetThickness("3"), nil)
  eq(ns.Config.GetSetting("thickness"), 3)
  truthy(ns.Config.SetThickness(0):match("thickness"))
  eq(ns.db.thickness, 3)
  eq(count(), 3)
end)
